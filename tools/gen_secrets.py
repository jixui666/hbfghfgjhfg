#!/usr/bin/env python3
"""构建期机密生成器。

每条敏感常量单独用 AES-256-GCM 加密（每条独立 nonce + AAD 绑定序号），
密文切成 4 段、随机打散写入 4 个互不相邻的静态数组，段偏移与段长分别存表。
Swift 侧只有 SecureBox 知道如何拼回并解密；明文不出现在任何产物里，
`strings` / 字节特征扫描都拿不到连续密文块。

用法:
    python tools/gen_secrets.py            # 生成 Swift 源
    python tools/gen_secrets.py --check    # 仅校验已生成文件是否最新
"""

import argparse
import hashlib
import hmac
import json
import os
import secrets as pysecrets
import sys

from cryptography.hazmat.primitives.ciphers.aead import AESGCM

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_DIR = os.path.join(ROOT, "ThreeOneOSFive", "Security", "Generated")
OUT_SWIFT = os.path.join(OUT_DIR, "Secrets.generated.swift")
PUBKEY_FILE = os.path.join(HERE, "integrity_pubkey.hex")

AAD_PREFIX = b"3105|"
INFO_PREFIX = "3105.blob."


def hkdf_sha256(ikm: bytes, salt: bytes, info: bytes, length: int = 32) -> bytes:
    """RFC 5869 HKDF-SHA256，与 CryptoKit HKDF<SHA256>.deriveKey 等价。"""
    prk = hmac.new(salt, ikm, hashlib.sha256).digest()
    okm = b""
    block = b""
    counter = 1
    while len(okm) < length:
        block = hmac.new(prk, block + info + bytes([counter]), hashlib.sha256).digest()
        okm += block
        counter += 1
    return okm[:length]


def random_split(data: bytes, parts: int = 4):
    n = len(data)
    if n < parts:
        data = data + b"\x00" * (parts - n)
        n = len(data)
    cuts = sorted(pysecrets.SystemRandom().sample(range(1, n), parts - 1))
    out = []
    prev = 0
    for c in cuts + [n]:
        out.append(data[prev:c])
        prev = c
    return out


def swift_bytes(b: bytes) -> str:
    return "[" + ", ".join("0x%02x" % x for x in b) + "]"


def load_config() -> dict:
    """优先 SECRETS_JSON 环境变量（CI secret），其次 tools/secrets.json，最后占位配置。

    仓库是公开的，所以真配置不进 git：本地放 tools/secrets.json（已 gitignore），
    CI 由 SECRETS_JSON secret 注入；两者都没有时用 sample 保证能编译（但连不上服务器）。
    """
    raw = os.environ.get("SECRETS_JSON", "").strip()
    if raw:
        print("[secrets] 使用 SECRETS_JSON 环境变量")
        return json.loads(raw)
    real = os.path.join(HERE, "secrets.json")
    if os.path.exists(real):
        print("[secrets] 使用 tools/secrets.json")
        return json.load(open(real, encoding="utf-8"))
    sample = os.path.join(HERE, "secrets.sample.json")
    print("[secrets][WARN] 没有 tools/secrets.json，退回占位配置 —— 编出来的包连不上服务器")
    return json.load(open(sample, encoding="utf-8"))


def build() -> int:
    cfg = load_config()

    entries = cfg["entries"]
    index = cfg["index"]

    salt_a = pysecrets.token_bytes(32)
    salt_b = pysecrets.token_bytes(32)
    master = bytes(x ^ y for x, y in zip(salt_a, salt_b))
    build_tag = pysecrets.token_bytes(4)

    shards = [bytearray(), bytearray(), bytearray(), bytearray()]
    layout = []
    lens = []

    for i, plain in enumerate(entries):
        key = hkdf_sha256(master, build_tag, (INFO_PREFIX + str(i)).encode())
        nonce = pysecrets.token_bytes(12)
        sealed = nonce + AESGCM(key).encrypt(nonce, plain.encode("utf-8"), AAD_PREFIX + str(i).encode())

        parts = random_split(sealed, 4)          # 顺序 = sealed 的原始顺序
        order = list(range(4))
        pysecrets.SystemRandom().shuffle(order)  # 只打乱"存到哪个 shard"

        rec = [0] * 8
        for slot, part in enumerate(parts):
            shard_id = order[slot]
            off = len(shards[shard_id])
            shards[shard_id] += part
            rec[slot * 2] = shard_id
            rec[slot * 2 + 1] = off
        layout.append(rec)
        for part in parts:
            lens.append(len(part))

    pubkey_hex = ""
    if os.path.exists(PUBKEY_FILE):
        pubkey_hex = open(PUBKEY_FILE).read().strip()
    pub = bytes.fromhex(pubkey_hex) if len(pubkey_hex) == 64 else b"\x00" * 32

    out = [
        "// Generated by tools/gen_secrets.py — DO NOT EDIT.",
        "// 每条敏感常量都是独立的 AES-256-GCM 密文（独立 nonce + AAD 绑定序号），",
        "// 切成 4 段随机打散存放在 4 个互不相邻的数组里。",
        "import Foundation",
        "",
        "enum GeneratedSecrets {",
        "    static let saltA: [UInt8] = %s" % swift_bytes(salt_a),
        "    static let saltB: [UInt8] = %s" % swift_bytes(salt_b),
        "    static let buildTag: [UInt8] = %s" % swift_bytes(build_tag),
        "",
    ]
    for i, sh in enumerate(shards):
        out.append("    static let shard%d: [UInt8] = %s" % (i, swift_bytes(bytes(sh))))
        out.append("")
    out.append("    /// 每个 entry 8 个整数: shardId0, off0, shardId1, off1, shardId2, off2, shardId3, off3")
    out.append("    static let layout: [[Int]] = [")
    for rec in layout:
        out.append("        [%s]," % ", ".join(str(v) for v in rec))
    out.append("    ]")
    out.append("")
    out.append("    /// 每个 entry 4 段的字节长度，顺序与 sealed 明文分段顺序一致")
    out.append("    static let lens: [Int] = [%s]" % ", ".join(str(v) for v in lens))
    out.append("")
    out.append("    /// 完整性清单的 Ed25519 验签公钥（私钥只在构建机 / CI secret 里）")
    out.append("    static let integrityPubKey: [UInt8] = %s" % swift_bytes(pub))
    out.append("")
    fp = hashlib.sha256(pub).digest()[:8]
    fp_val = int.from_bytes(fp, "big")
    out.append("    /// sha256(pubkey) 前 8 字节。写成无存储的计算属性：-O 会内联成")
    out.append("    /// __TEXT 里的立即数/literal pool。企业签工具会丢掉自定义 section，")
    out.append("    /// 但指纹在 __TEXT 里就够了——改 __DATA 的公钥或数组会与指纹失配，")
    out.append("    /// 改指纹自己则会破坏 textHash，闭环仍然成立。")
    out.append("    static var integrityFingerprint: UInt64 { 0x%016x }" % fp_val)
    out.append("")
    out.append("    enum ID: Int, CaseIterable {")
    for name, pos in index.items():
        out.append("        case %s = %d" % (name, pos))
    out.append("    }")
    out.append("}")
    out.append("")

    text = "\n".join(out)
    os.makedirs(OUT_DIR, exist_ok=True)

    if "--check" in sys.argv:
        old = open(OUT_SWIFT, encoding="utf-8").read() if os.path.exists(OUT_SWIFT) else ""
        ok = old == text
        print("generated file up to date:", ok)
        return 0 if ok else 1

    with open(OUT_SWIFT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)

    print("wrote", OUT_SWIFT)
    print("  entries     :", len(entries))
    print("  shard sizes :", [len(s) for s in shards])
    print("  pubkey      :", pub.hex() if pub != b"\x00" * 32 else "PLACEHOLDER (run tools/keygen.py)")
    return 0


if __name__ == "__main__":
    sys.exit(build())
